// Generates lib/features/workspace/domain/warp_model_caps_table.dart from the
// Param_<model>_<variant>_<panel>.xml files that ship with Panasonic's
// projector software (its CommandXML folder).
//
//   dart run tool/generate_warp_model_caps.dart [CommandXML folder] [output file]
//
// Run it from the repository root. The folder defaults to the Windows install
// path of the software. The script stops without writing anything when a file
// lacks a parameter the table needs, so a newer release that renames one is
// noticed instead of silently dropping models.
import 'dart:io';

const _defaultFolder =
    r'C:\Program Files\Panasonic\Visual Software Suite\CommandXML';
const _defaultOutput =
    'lib/features/workspace/domain/warp_model_caps_table.dart';

/// Param name -> field of WarpModelCaps, in the order they are written.
const _fields = <(String, String, bool)>[
  ('GEO_WARP_DATA_BIT_TYPE', 'bits', false),
  ('GEO_WARP_INNER_SIZE_HOR', 'panelWidth', false),
  ('GEO_WARP_INNER_SIZE_VER', 'panelHeight', false),
  ('GEO_WARP_VIEW_SIZE_HOR', 'viewWidth', false),
  ('GEO_WARP_VIEW_SIZE_VER', 'viewHeight', false),
  ('GEO_GRID_TABLE_SIZE_HOR', 'tableColumns', false),
  ('GEO_GRID_TABLE_SIZE_VER', 'tableRows', false),
  ('GEO_GRID_STEP_SIZE_HOR', 'stepX', false),
  ('GEO_GRID_STEP_SIZE_VER', 'stepY', false),
  ('GEO_MOVABLE_RANGE_HOR', 'movableRangeX', false),
  ('GEO_MOVABLE_RANGE_VER', 'movableRangeY', false),
  ('GEO_IS_4K_FPGA', 'is4kFpga', true),
  ('GEO_IS_GCX2', 'isGcx2', true),
  ('GEO_IS_SCX4', 'isScx4', true),
  ('GEO_IS_NO_INVERSE', 'isNoInverse', true),
  ('GEO_CURSOR_SELECT', 'cursorSelect', false),
  ('GEO_DISPLAY_ADJ_POINTS', 'displayAdjPoints', false),
];

final _param = RegExp(
  r'<ParamName>\s*([^<\s]+)\s*</ParamName>\s*<ParamValue>\s*([^<]*?)\s*</ParamValue>',
);
final _fileName = RegExp(
  r'^Param_([0-9a-fA-F]{2,4}_[0-9a-zA-Z]{2}_[0-9a-zA-Z]{2})\.xml$',
);

void main(List<String> args) {
  final folder = Directory(args.isNotEmpty ? args[0] : _defaultFolder);
  final output = File(args.length > 1 ? args[1] : _defaultOutput);
  if (!folder.existsSync()) {
    stderr.writeln('Folder not found: ${folder.path}');
    exit(2);
  }

  final files =
      folder
          .listSync()
          .whereType<File>()
          .where((f) => f.uri.pathSegments.last.startsWith('Param_'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final rows = <String, Map<String, int>>{};
  final problems = <String>[];

  for (final file in files) {
    final name = file.uri.pathSegments.last;
    final id = _fileName.firstMatch(name)?.group(1)?.toLowerCase();
    if (id == null) {
      problems.add('$name: unexpected file name');
      continue;
    }
    final values = {
      for (final m in _param.allMatches(file.readAsStringSync()))
        m.group(1)!: m.group(2)!,
    };
    final row = <String, int>{};
    for (final (param, field, _) in _fields) {
      final text = values[param];
      final value = text == null ? null : int.tryParse(text);
      if (value == null) {
        problems.add(
          '$name: $param is ${text == null ? 'missing' : 'not a number ("$text")'}',
        );
      } else {
        row[field] = value;
      }
    }
    rows[id] = row;
  }

  if (problems.isNotEmpty || rows.isEmpty) {
    stderr.writeln('Nothing written. Problems:');
    for (final p in problems) {
      stderr.writeln('  $p');
    }
    if (rows.isEmpty) stderr.writeln('  no Param_*.xml files found');
    exit(1);
  }

  final ids = rows.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT EDIT.')
    ..writeln('//')
    ..writeln('// Generated by tool/generate_warp_model_caps.dart from the')
    ..writeln(
      "// Param_*.xml files of Panasonic's projector software: ${ids.length} rows.",
    )
    ..writeln(
      '// Run `dart run tool/generate_warp_model_caps.dart` to regenerate.',
    )
    ..writeln()
    ..writeln("import 'warp_model_caps.dart';")
    ..writeln()
    ..writeln(
      '/// One row per Param file, keyed by file id (`<model>_<variant>_<panel>`).',
    )
    ..writeln('const Map<String, WarpModelCaps> warpModelCapsTable = {');
  for (final id in ids) {
    out
      ..writeln("  '$id': WarpModelCaps(")
      ..writeln("    id: '$id',");
    for (final (_, field, isFlag) in _fields) {
      final value = rows[id]![field]!;
      out.writeln('    $field: ${isFlag ? value != 0 : value},');
    }
    out.writeln('  ),');
  }
  out.writeln('};');

  output.writeAsStringSync(out.toString());
  stdout.writeln(
    'Wrote ${ids.length} rows from ${files.length} files to ${output.path}',
  );
}
